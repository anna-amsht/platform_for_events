    public String answer(String question) {
        String normalized = normalize(question);
        return topics.stream()
                .filter(topic -> topic.matches(normalized))
                .findFirst()
                .map(InstructionTopic::answer)
                .orElse(DEFAULT_ANSWER);
    }

    private String normalize(String value) {
        return value == null ? "" : value.toLowerCase(Locale.ROOT).trim();
    }

    private record InstructionTopic(List<String> keywords, String answer) {
        private boolean matches(String question) {
            return keywords.stream().anyMatch(question::contains);
        }
    }
